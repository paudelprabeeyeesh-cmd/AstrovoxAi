def build() -> list[dict]:
    topics = []
    for sec_num, level, sec_name, items in SECTIONS:
        for topic_num, name in items:
            topics.append({
                "id": f"S{sec_num}.T{topic_num:03d}",
                "topic_number": topic_num,
                "section": sec_num,
                "section_name": sec_name,
                "level": level,
                "name": name,
                "status": status_for(topic_num),
                "domain": sec_name.split(":")[0],
                "subdomain": sec_name,
                "prerequisites": [],
                "difficulty": min(5, max(1, (topic_num - 1) // 170 + 1)),
                "implementation_module": f"math_engine.{_module_for(sec_num)}",
                "operations": [f"compute_{topic_num}"],
                "dependencies": ["numpy", "sympy"],
                "ai_application": "AstraVox AI math capability",
                "verified": False,
            })
    return topics


