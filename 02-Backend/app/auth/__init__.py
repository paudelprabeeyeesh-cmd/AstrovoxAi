"""Authentication and authorization package for the AstrovoxAI backend.

Security rules enforced by this module (see docs/THREAT_MODEL.md C1, C8, C9):

* Imports live at the top of the file. Nothing below uses a name that is
  imported later, because a function defined before its import only works
  until the first call raises NameError.
* No secret-bearing value is ever returned in a response body. Verification
  tokens, magic-link tokens, and reset tokens are delivered by email and
  are single-use. Returning them to the caller bypasses email ownership
  of the account and is a full account-takeover primitive.
* Tokens are generated by ``secrets.token_urlsafe`` with 256 bits of
  entropy. uuid4 concatenation is not a token API: it is time-and-random
  seeded, only 122 bits, and exposed in a predictor form.
* Every request model uses ``EmailStr`` and length limits so a malformed
  body is rejected at the edge rather than deep in a provider call.
* Every mutation is audited on both the success and the failure path.

``app/auth/`` (this package) and ``app/auth.py`` (module) historically shared
a name; the package wins the import. The legacy module is loaded explicitly
so the historical import surface stays available.
"""
