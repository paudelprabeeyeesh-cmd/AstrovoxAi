@router.post("/oauth")
@limiter.limit("5/minute")
async def oauth_login(request: Request, body: OAuthLoginRequest):
    """Exchange a verified provider token for a session (D06-02).

    The provider must be in the allowlist, and the provider's userinfo
    endpoint must confirm the subject and the email. Only then is a
    session issued for that identity. An unverified email in the request
    body cannot mint a session.
    """
    if body.provider not in OAUTH_PROVIDERS:
        _audit.record(
            actor=body.email or "anonymous",
            action="auth_oauth",
            target="user",
            outcome="failed",
            metadata={"reason": "unknown_provider", "provider": body.provider},
        )
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Unsupported provider",
        )

    claims = _verify_provider_access_token(body.provider, body.access_token)
    if not claims or not claims.get("sub"):
        _audit.record(
            actor=body.email or "anonymous",
            action="auth_oauth",
            target="user",
            outcome="failed",
            metadata={"reason": "token_verification_failed", "provider": body.provider},
        )
        _dispatch_security_event(
            "auth_oauth_failed", body.email or "anonymous",
            f"OAuth token verification failed for {body.provider}",
            severity="high",
        )
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid provider token",
        )

    provider_sub = str(claims["sub"])
    verified_email = (claims.get("email") or "").strip().lower()
    if not verified_email:
        _audit.record(
            actor=provider_sub,
            action="auth_oauth",
            target="user",
            outcome="failed",
            metadata={"reason": "no_email_from_provider", "provider": body.provider},
        )
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Provider did not return an email address",
        )

    if body.email and body.email.lower() != verified_email:
        _audit.record(
            actor=provider_sub,
            action="auth_oauth",
            target="user",
            outcome="failed",
            metadata={"reason": "email_mismatch", "provider": body.provider},
        )
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Provider email does not match the supplied email",
        )

    user = _resolve_oauth_subject(body.provider, provider_sub, verified_email)
    _audit.record(
        actor=user["id"],
        action="auth_oauth",
        target="user",
        outcome="success",
        metadata={"provider": body.provider, "ip": _client_ip(request)},
    )
    _dispatch_security_event(
        "auth_oauth", user["id"],
        f"OAuth sign-in via {body.provider}", severity="low",
    )
    return {
        "status": "OK",
        "provider": body.provider,
        "message": "OAuth sign-in verified",
        "user": {"id": user["id"], "email": verified_email},
    }


def _verify_provider_access_token(provider: str, access_token: str) -> Optional[dict]:
    """Validate the access token against the provider's userinfo endpoint.

    Returns the claims on success, None on any failure. Network failures,
    unexpected status codes, and parse errors all collapse to None: an
    undetermined identity is never an authorized one.
    """
    if provider not in OAUTH_PROVIDERS:
        return None
    userinfo_url = OAUTH_PROVIDERS[provider].get("userinfo_url")
    if not userinfo_url:
        return None

    import requests

    try:
        resp = requests.get(
            userinfo_url,
            headers={
                "Authorization": f"Bearer {access_token}",
                "Accept": "application/json",
            },
            timeout=10,
        )
        if resp.status_code != 200:
            return None
        data = resp.json()
        # OIDC subject; GitHub uses "id" and OIDC providers use "sub".
        sub = data.get("sub") or data.get("id")
        if not sub:
            return None
        email = data.get("email")
        if email and not data.get("email_verified", True):
            return None
        return {"sub": sub, "email": email}
    except Exception:  # noqa: BLE001 - any failure means "not verified"
        logger.warning("oauth.userinfo_failed provider=%s", provider)
        return None


def _resolve_oauth_subject(provider: str, provider_sub: str, email: str) -> dict:
    """Return the local user bound to this verified provider subject."""
    from app.database import get_db

    with get_db() as conn:
        row = conn.execute(
            "SELECT * FROM oauth_accounts WHERE provider=? AND provider_user_id=?",
            (provider, provider_sub),
        ).fetchone()
        if row:
            return {"id": row["user_id"], "provider_account": dict(row)}
        from app.services.oauth_service import get_or_create_oauth_user

        user = get_or_create_oauth_user(
            provider=provider,
            provider_user_id=provider_sub,
            email=email,
        )
        return {"id": user["id"], "provider_account": None}


@router.post("/refresh")
@limiter.limit("20/minute")
async def refresh_token(request: Request, body: RefreshTokenRequest):
    """Rotate a refresh token.

    The token arrives in the JSON body, never in a query string: query
    strings land in access logs, browser history, and proxy logs.
    """
    incoming = body.refresh_token
    try:
        response = supabase.auth.refresh_session(incoming)
        session = response.session if response else None
        if not session:
            _audit.record(
                actor="anonymous",
                action="auth_refresh",
                target="session",
                outcome="failed",
                metadata={"reason": "invalid_refresh_token"},
            )
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid refresh token"
            )
    except HTTPException:
        raise
    except Exception as exc:  # noqa: BLE001
        _audit.record(
            actor="anonymous",
            action="auth_refresh",
            target="session",
            outcome="failed",
            metadata={"error": str(exc)[:100]},
        )
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED, detail="Failed to refresh token"
        ) from exc

    user_id = str(response.user.id) if response.user else "anonymous"
    try:
        new_refresh_token, rotated = refresh_token_rotation.rotate(incoming, user_id)
    except ValueError:
        _audit.record(
            actor=user_id,
            action="auth_refresh",
            target="session",
            outcome="failed",
            metadata={"reason": "refresh_token_reuse"},
        )
        _dispatch_security_event(
            "refresh_token_reuse", user_id,
            "Refresh token reuse detected - sessions revoked",
            severity="critical",
        )
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED, detail="Refresh token reuse detected"
        )

    _audit.record(
        actor=user_id,
        action="auth_refresh",
        target="session",
        outcome="success",
    )
    return {
        "status": "OK",
        "session": {
            "access_token": session.access_token,
            "refresh_token": new_refresh_token if rotated else incoming,
        },
    }


