# Tokens are delivered by email. A reset link is long-lived because the
# user has to leave the tab, find the mail, and come back; a verification
# link is longer still. Both are single use, so "long" is about the human
# trip, not about a long attack window.
VERIFICATION_TOKEN_TTL_HOURS = 24
RESET_TOKEN_TTL_HOURS = 1
MAX_TOKEN_BYTES = 4096


class SecurityEvent:
    def __init__(self, event_type, severity, user_id, description, timestamp, metadata):
        self.event_type = event_type
        self.severity = severity
        self.user_id = user_id
        self.description = description
        self.timestamp = timestamp
        self.metadata = metadata


def _dispatch_security_event(event_type: str, user_id: str, description: str,
                             severity: str = "medium", metadata: Optional[dict] = None) -> None:
    if security_event_webhook is None:
        return
    security_event_webhook.dispatch(SecurityEvent(
        event_type=event_type,
        severity=severity,
        user_id=user_id,
        description=description,
        timestamp=time.time(),
        metadata=metadata or {},
    ))


def _new_token() -> str:
    """A single-use, 256-bit, URL-safe token.

    ``secrets`` is the CSPRNG primitive; uuid4 is an identifier generator.
    Substituting one for the other is the difference between a token nobody
    can predict and a token an attacker can narrow down.
    """
    return secrets.token_urlsafe(32)


def _client_ip(request: Request) -> str:
    """Real client IP behind a reverse proxy.

    ``request.client.host`` is the *proxy's* address when nginx fronts the
    app, which collapses every user into one rate-limit bucket. The
    forwarded value is only trusted when the app is told to trust the
    proxy, so an untrusted client cannot forge a bucket to hide in.
    """
    trusted = os.getenv("TRUST_PROXY_HEADERS", "false").lower() in ("1", "true", "yes")
    if trusted:
        forwarded = request.headers.get("x-forwarded-for", "")
        if forwarded:
            first = forwarded.split(",")[0].strip()
        else:
            first = forwarded
        if first:
            return first
    return request.client.host if request.client else "unknown"


