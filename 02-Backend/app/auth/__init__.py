def create_access_token(user_id: str, email: str = "", expires_in: int = 3600) -> str:
    """Mint a service-issued JWT for internal/test flows."""
    payload = {
        "sub": user_id,
        "email": email,
        "iat": int(time.time()),
        "exp": int(time.time()) + int(expires_in),
        "jti": _new_token()[:16],
    }
    secret = os.getenv("SECRET_KEY", "")
    if not secret:
        raise RuntimeError("SECRET_KEY is not set; refusing to sign a token")
    import base64
    import hashlib
    import hmac
    import json

    def _b64(raw: bytes) -> str:
        return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()

    head = _b64(json.dumps({"alg": "HS256", "typ": "JWT"}, separators=(",", ":")).encode())
    body = _b64(json.dumps(payload, separators=(",", ":")).encode())
    signature = _b64(hmac.new(
        secret.encode(), f"{head}.{body}".encode(), hashlib.sha256
    ).digest())
    return f"{head}.{body}.{signature}"


