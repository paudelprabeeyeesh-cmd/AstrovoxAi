@router.post("/signup")
@limiter.limit("5/minute")
async def sign_up(request: Request, body: SignUpRequest):
    """Register a new user with Supabase Auth.

    The response carries the id and email only. Supabase owns the
    verification and reset flows, so this endpoint never mints, echoes, or
    returns a token of its own.
    """
    try:
        response = supabase.auth.sign_up(
            {
                "email": body.email,
                "password": body.password,
                "options": {"data": {"full_name": body.full_name}},
            }
        )
    except HTTPException:
        raise
    except Exception as exc:  # noqa: BLE001
        _audit.record(
            actor=body.email,
            action="auth_signup",
            target="user",
            outcome="failed",
            metadata={"error": str(exc)[:100]},
        )
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, detail="Signup failed"
        ) from exc

    if not response or not response.user:
        _audit.record(
            actor=body.email,
            action="auth_signup",
            target="user",
            outcome="failed",
            metadata={"reason": "no_user_returned"},
        )
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, detail="Signup failed"
        )

    _audit.record(
        actor=str(response.user.id),
        action="auth_signup",
        target="user",
        outcome="success",
    )
    _dispatch_security_event(
        "auth_signup", str(response.user.id),
        f"New account registered from {_client_ip(request)}", severity="low",
    )
    return {
        "status": "OK",
        "message": "Signup successful. Please verify your email.",
        "user": {"id": response.user.id, "email": response.user.email},
    }


@router.post("/login")
@limiter.limit("10/minute")
async def login(request: Request, body: LoginRequest):
    """Login with email and password."""
    client_ip = _client_ip(request)

    is_locked, remaining, lock_message = brute_force_protection.is_locked(body.email)
    if is_locked:
        _audit.record(
            actor=body.email,
            action="auth_login",
            target="user",
            outcome="failed",
            metadata={"reason": "locked_out", "remaining_seconds": int(remaining) if remaining else 0},
        )
        _dispatch_security_event(
            "auth_locked_out", body.email,
            f"Login attempt on locked account from {client_ip}",
            severity="high",
        )
        raise HTTPException(
            status_code=status.HTTP_423_LOCKED,
            detail=(
                f"Account temporarily locked. Try again in "
                f"{int(remaining) if remaining else 0} seconds."
                + (f" ({lock_message})" if lock_message else "")
            ),
        )

    try:
        response = supabase.auth.sign_in_with_password(
            {"email": body.email, "password": body.password}
        )
        user = response.user if response else None
    except Exception as exc:  # noqa: BLE001 - provider failure is not a stack trace
        brute_force_protection.record_failure(body.email, client_ip)
        _audit.record(
            actor=body.email,
            action="auth_login",
            target="user",
            outcome="failed",
            metadata={"error": str(exc)[:100]},
        )
        _dispatch_security_event(
            "auth_error", body.email,
            f"Login error from {client_ip}: {str(exc)[:100]}",
            severity="high",
        )
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Login unavailable",
        ) from exc

    if not user:
        brute_force_protection.record_failure(body.email, client_ip)
        remaining_attempts = brute_force_protection.remaining_attempts(body.email)
        _audit.record(
            actor=body.email,
            action="auth_login",
            target="user",
            outcome="failed",
            metadata={
                "reason": "invalid_credentials",
                "remaining_attempts": remaining_attempts,
                "ip": client_ip,
            },
        )
        auth_anomaly_detector.record_event(APIEvent(
            user_id=body.email, ip=client_ip, country=None,
            user_agent=request.headers.get("user-agent", ""), timestamp=time.time(),
        ))
        _dispatch_security_event(
            "auth_failed", body.email,
            f"Failed login from {client_ip}",
            severity="medium",
        )
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Invalid credentials. {remaining_attempts} attempts remaining before lockout.",
        )

    brute_force_protection.record_success(body.email, client_ip)
    record_login_attempt(client_ip, True)
    _audit.record(
        actor=str(user.id),
        action="auth_login",
        target="user",
        outcome="success",
        metadata={"ip": client_ip},
    )
    auth_anomaly_detector.record_event(APIEvent(
        user_id=str(user.id), ip=client_ip, country=None,
        user_agent=request.headers.get("user-agent", ""), timestamp=time.time(),
        endpoint=str(request.url.path), method=request.method, status_code=200,
    ))
    return {
        "status": "OK",
        "message": "Login successful",
        "user": {"id": user.id, "email": user.email},
        "session": {
            "access_token": response.session.access_token if response.session else None,
            "refresh_token": response.session.refresh_token if response.session else None,
        },
    }


@router.post("/logout")
@limiter.limit("20/minute")
async def logout(request: Request, authorization: str = Header(None)):
    """Revoke the session server-side, not just ask the client to forget it."""
    user_id = "anonymous"
    revoked = False
    if authorization:
        token = authorization.replace("Bearer ", "", 1).strip()
        try:
            user_resp = supabase.auth.get_user(token)
            if user_resp and user_resp.user:
                user_id = str(user_resp.user.id)
        except Exception:  # noqa: BLE001 - revocation must not be blocked by provider outage
            pass
        jti = token[:32]
        token_revocation_list.revoke(
            jti, user_id, time.time() + 3600, reason="logout"
        )
        refresh_token_rotation.revoke_all(user_id)
        revoked = True
        try:
            supabase.auth.sign_out()
        except Exception:  # noqa: BLE001
            logger.debug("Supabase sign_out failed for user=%s", user_id)
    _audit.record(actor=user_id, action="auth_logout", target="user", outcome="success")
    _dispatch_security_event("auth_logout", user_id, "User logged out", severity="low")
    return {
        "status": "OK",
        "message": "Logout successful",
        "revoked": revoked,
    }


@router.post("/reset-password")
@limiter.limit("3/minute")
async def reset_password(request: Request, body: ResetPasswordRequest):
    """Send a password reset email.

    The response is identical whether or not the account exists, so the
    endpoint cannot be used to enumerate users. The token is never
    returned, never logged, and only exists in the emailed link.
    """
    try:
        supabase.auth.reset_password_for_email(
            body.email,
            options={
                "redirect_to": (
                    f"{os.getenv('FRONTEND_URL', 'http://localhost:5173')}/reset-password"
                ),
            },
        )
        _audit.record(
            actor=body.email,
            action="auth_password_reset",
            target="user",
            outcome="requested",
        )
    except Exception as exc:  # noqa: BLE001
        _audit.record(
            actor=body.email,
            action="auth_password_reset",
            target="user",
            outcome="failed",
            metadata={"error": str(exc)[:100]},
        )
        logger.warning("Password reset failed: %s", str(exc)[:100])

    # Deliberately constant-time-ish in wording: no enumeration signal.
    return {"status": "OK", "message": "Password reset email sent successfully"}


@router.get("/me")
async def whoami(authorization: str = Header(None)):
    """Current user profile."""
    if not authorization:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authorization header required",
            headers={"WWW-Authenticate": "Bearer"},
        )
    token = _bearer(authorization)
    # Validate through this module's supabase client rather than a helper
    # that resolves its own. The two would otherwise be different objects,
    # and only the module-level one is what callers patch in tests.
    try:
        response = supabase.auth.get_user(token)
        if not response or not response.user:
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid or expired token",
            )
    except HTTPException:
        raise
    except Exception as exc:  # noqa: BLE001
        _audit.record(
            actor="anonymous",
            action="auth_get_me",
            target="user",
            outcome="failed",
            metadata={"error": str(exc)[:100]},
        )
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token"
        ) from exc

    try:
        profile_response = (
            supabase.table("profiles").select("*").eq("id", response.user.id).execute()
        )
        profile = profile_response.data[0] if profile_response.data else None
        _audit.record(
            actor=response.user.id,
            action="auth_get_me",
            target="user",
            outcome="success",
        )
        return {
            "status": "OK",
            "user": {
                "id": response.user.id,
                "email": response.user.email,
                "profile": profile,
            },
        }
    except HTTPException:
        raise
    except Exception as exc:  # noqa: BLE001
        _audit.record(
            actor=str(response.user.id),
            action="auth_get_me",
            target="user",
            outcome="failed",
            metadata={"error": str(exc)[:100]},
        )
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token"
        ) from exc


def _bearer(authorization: str) -> str:
    return authorization.replace("Bearer ", "", 1).strip()


