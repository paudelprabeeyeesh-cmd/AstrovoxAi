async def require_verified_email(request: Request, authorization: str = Header(None)) -> str:
    """Resolve the caller and require a verified email address.

    A valid token is not enough: it must not have been revoked (logout) and
    the account's email must be verified. Delegating to token validation
    alone let any authenticated-but-unverified user through, which is the
    exact boundary ``require_verified_email`` is supposed to guard.
    """
    if not authorization:
        authorization = request.headers.get("authorization", "")
    if not authorization:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authorization header required",
            headers={"WWW-Authenticate": "Bearer"},
        )
    token = authorization.replace("Bearer ", "", 1).strip()

    # P0-5: a token invalidated by logout must not authenticate.
    if token_revocation_list.is_revoked(token[:32]):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Token has been revoked",
            headers={"WWW-Authenticate": "Bearer"},
        )

    user = None
    try:
        response = supabase.auth.get_user(token)
        user = response.user if response else None
    except Exception:
        pass
    if not user:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired token",
            headers={"WWW-Authenticate": "Bearer"},
        )

    # P0-3: verified email is required, not merely a valid token.
    if not _email_is_verified(user):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Email verification required",
        )
    return str(user.id)


def _email_is_verified(user: object) -> bool:
    """Return True only when the provider reports a confirmed email.

    Supabase sets ``email_confirmed_at`` once email ownership is proven; a
    null/empty value means the account is authenticated but unverified.
    """
    if user is None:
        return False
    if getattr(user, "email_confirmed_at", None) or getattr(user, "confirmed_at", None):
        return True
    for meta in (getattr(user, "app_metadata", None), getattr(user, "user_metadata", None)):
        if isinstance(meta, dict) and (meta.get("email_verified") is True or meta.get("email_confirmed_at")):
            return True
    return False


async def require_admin(request: Request, authorization: str = Header(None)) -> str:
    """Admin gate. Delegates to role_required so one code path owns the rule."""
    return role_required("admin")(authorization)


async def get_principal(request: Request) -> Any:
    authorization = request.headers.get("authorization", "")
    if not authorization:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authorization header required",
            headers={"WWW-Authenticate": "Bearer"},
        )
    user = await get_current_user(request)
    if not user:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired token",
            headers={"WWW-Authenticate": "Bearer"},
        )
    return user


def _require_token(authorization: Optional[str]) -> str:
    if not authorization:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authorization header required",
            headers={"WWW-Authenticate": "Bearer"},
        )
    user_id = get_user_id_from_token(authorization)
    if not user_id:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired token",
            headers={"WWW-Authenticate": "Bearer"},
        )
    return user_id


def get_user_id_from_token_with_roles(authorization: Optional[str] = Header(None)) -> dict:
    """Resolve the principal and its roles from the Supabase access token."""
    if not authorization:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authorization header required",
        )
    try:
        token = authorization.replace("Bearer ", "")
        response = supabase.auth.get_user(token)
        if not response.user:
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid or expired token",
            )
        user = response.user
        roles: list[str] = []
        app_metadata = getattr(user, "app_metadata", {}) or {}
        if not hasattr(app_metadata, "get"):
            app_metadata = {}
        raw_roles = app_metadata.get("roles", [])
        if isinstance(raw_roles, list):
            roles = [str(r) for r in raw_roles]
        elif isinstance(raw_roles, str):
            roles = [raw_roles]
        return {"user_id": user.id, "roles": roles}
    except HTTPException:
        raise
    except Exception:  # noqa: BLE001 - provider failure is a 401, not a stack trace
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token"
        )


def role_required(role: str):
    def _dependency(authorization: Optional[str] = Header(None)):
        info = get_user_id_from_token_with_roles(authorization)
        if role not in info["roles"]:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail=f"Role '{role}' required",
            )
        return info["user_id"]
    return _dependency


def get_current_user(authorization: Optional[str] = Header(None)):
    """Return the caller's user id, or raise 401. Single definition, one path."""
    info = get_user_id_from_token_with_roles(authorization)
    return info["user_id"]


